// Whitelist cứng: luôn bỏ qua dù bất kỳ thể loại nào
const WHITELIST_WORDS = new Set([
    // Đơn vị đo lường quốc tế
    'km', 'cm', 'm', 'kg', 'mb', 'gb', 'tb', 'fps', 'id', 'ip', 'ok',
    // Thuật ngữ tu tiên / xuyên thể / thường thấy trong văn học TQ dịch
    'sect', 'dao', 'qi', 'chi', 'dojo', 'wuxia', 'xianxia',
    // Tên viết tắt phổ biến
    'mc', 'npc', 'hp', 'mp', 'sp', 'exp', 'vip', 'ai', 'ar', 'vr',
]);

const EN_WORD_PATTERN = /(?<!\p{L})([a-zA-Z]+(?:[''][a-zA-Z]+)?(?:\s+[a-zA-Z]+(?:[''][a-zA-Z]+)?){0,6})(?!\p{L})/gu;

const VI_ACCENT_CHARS = /[àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđÀÁẠẢÃÂẦẤẬẨẪĂẰẮẶẲẴÈÉẸẺẼÊỀẾỆỂỄÌÍỊỈĨÒÓỌỎÕÔỒỐỘỔỖƠỜỚỢỞỠÙÚỤỦŨƯỪỨỰỬỮỲÝỴỶỸĐ]/;

const isProperNoun = (word: string): boolean => {
    if (/^[A-Z]{2,}$/.test(word)) return true;
    if (/^[A-Z][a-z]/.test(word)) return true;
    return false;
};

const isVietnameseSentence = (line: string): boolean => {
    return VI_ACCENT_CHARS.test(line);
};

export interface EnglishInlineMatch {
    line: number;
    original: string;
    fixed: string;
    changes: { found: string; replaced: string }[];
}

export const fixInlineEnglish = (
    text: string,
    extraMap?: Record<string, string>
): { fixed: string; changes: { line: number; found: string; replaced: string }[] } => {
    if (!text) return { fixed: text, changes: [] };

    const allChanges: { line: number; found: string; replaced: string }[] = [];
    
    // Sort by length DESC for longest-match-first
    const combinedMap: Record<string, string> = { ...COMMON_EN_VI_MAP, ...(extraMap || {}) };
    const sortedEntries = Object.entries(combinedMap).sort((a, b) => b[0].length - a[0].length);

    const lines = text.split('\n');
    const processedLines = lines.map((line, lineIndex) => {
        if (!line.trim()) return line;
        
        if (!isVietnameseSentence(line)) return line;
        
        // Bỏ qua dòng tiêu đề chương (số Ả Rập, chữ Hán, La Mã)
        if (/^(Chương|Hồi|Phần|Quyển|Tập|Tiết|Chapter|第)\s*[\d一二三四五六七八九十百千万]+/i.test(line.trim())) return line;
        // Bỏ qua dòng ngắn < 5 từ (có thể là tên riêng hoặc tiêu đề phụ)
        if (line.trim().split(/\s+/).length < 5 && /^[A-Z]/.test(line.trim())) return line;
        
        let processedLine = line;
        
        for (const [enPhrase, viPhrase] of sortedEntries) {
            const escaped = enPhrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/'/g, "['']");
            
            const regex = new RegExp(
                `(?<![A-Za-zÀ-ỹ])${escaped}(?![A-Za-zÀ-ỹ])`,
                'gi'
            );
            
            const newLine = processedLine.replace(regex, (match, offset, fullLine) => {
                const isStartOfSentence = offset === 0 || /(?:^|[.!?]\s+)["'“‘«(]?$|^\s+$/.test(fullLine.substring(0, offset));
                
                if (isProperNoun(match.trim()) && !isStartOfSentence) return match;
                if (WHITELIST_WORDS.has(match.toLowerCase())) return match;
                
                allChanges.push({ line: lineIndex, found: match, replaced: viPhrase });
                
                // Keep original capitalization if it was capitalized
                if (/^[A-Z]/.test(match) && viPhrase.length > 0) {
                     return viPhrase.charAt(0).toUpperCase() + viPhrase.slice(1);
                }
                return viPhrase;
            });
            
            processedLine = newLine;
        }
        
        return processedLine;
    });

    return { fixed: processedLines.join('\n'), changes: allChanges };
};

export const detectUnmappedInlineEnglish = (
    text: string,
    dictionaryText: string = "",
    contextText: string = "",
    promptText: string = "",
    genres: string[] = []
): {
    lineIndex: number;
    line: string;
    enWords: string[];
}[] => {
    if (!text) return [];
    
    const customWhitelist = new Set<string>();
    const extractToWhitelist = (source: string) => {
        if (!source) return;
        const matches = source.match(/[a-zA-Z]+/g);
        if (matches) {
            matches.forEach(m => {
                if (m.length > 2) customWhitelist.add(m.toLowerCase());
            });
        }
    };
    extractToWhitelist(dictionaryText);
    extractToWhitelist(contextText);
    extractToWhitelist(promptText);
    
    const results: { lineIndex: number; line: string; enWords: string[] }[] = [];
    const lines = text.split('\n');
    
    const isModernOrGame = genres.some(g => ['Light Novel', 'Võng Du', 'Đô Thị', 'Mạt Thế', 'Khoa Huyễn', 'Hệ Thống', 'Đồng Nhân', 'Hài Hước', 'Fantasy', 'Action', 'Isekai', 'Game', 'Hiện Đại'].includes(g));

    const GAME_MODERN_WHITELIST = new Set([
        'wifi', 'boss', 'level', 'skill', 'hack', 'hacker', 'app', 'web', 'internet', 'online', 'offline',
        'game', 'gamer', 'livestream', 'streamer', 'fan', 'idol', 'vip', 'pro', 'pc', 'laptop', 'smartphone',
        'email', 'mail', 'chat', 'post', 'status', 'share', 'like', 'comment', 'view', 'follow',
        'follower', 'sub', 'subscribe', 'youtube', 'facebook', 'tiktok', 'twitter', 'instagram', 'google',
        'apple', 'samsung', 'bar', 'club', 'pub', 'dj', 'mc', 'hot', 'hotgirl', 'hotboy', 'sexy', 'show',
        'showbiz', 'camera', 'video', 'clip', 'live', 'ok', 'oke', 'yes', 'no', 'bye', 'hello', 'hi',
        'sorry', 'thanks', 'thank', 'you', 'oh', 'wow', 'oops', 'hey', 'yo',
        'yeah', 'sure', 'wtf', 'omg', 'fake', 'real', 'trend', 'scandal', 'drama', 'hit', 'top',
        'ad', 'admin', 'mod', 'sp', 'support', 'hp', 'mp', 'exp', 'npc', 'pk', 'pvp', 'pve', 'bug',
        'lag', 'ping', 'map', 'item', 'gold', 'coin', 'buff', 'nerf', 'tank', 'dps', 'heal', 'healer',
        'carry', 'mid', 'jungle', 'gank', 'solo', 'team', 'guild', 'clan', 'party', 'rank',
        'match', 'win', 'lose', 'gg', 'afk', 'noob', 'bot', 'tool', 'auto', 'macro', 'combo',
        'crit', 'dame', 'damage', 'def', 'armor', 'mana', 'stamina', 'speed', 'agi', 'str',
        'int', 'dex', 'vit', 'luck', 'rate', 'drop', 'box', 'chest', 'quest', 'mission', 'event', 'shop',
        'store', 'buy', 'sell', 'trade', 'pay', 'cash', 'card', 'visa', 'mastercard', 'atm', 'bank',
        'ios', 'android', 'windows', 'mac', 'linux', 'ui', 'ux', 'code', 'fix', 'update',
        'patch', 'version', 'beta', 'alpha', 'test', 'server', 'client', 'host', 'ip', 'port', 'dns',
        'url', 'link', 'click', 'tap', 'swipe', 'scroll', 'zoom', 'max', 'min', 'pro', 'svip', 'idol'
    ]);
    
    lines.forEach((line, lineIndex) => {
        if (!line.trim()) return;
        if (!isVietnameseSentence(line)) return;
        // Bỏ qua dòng tiêu đề chương (số Ả Rập, chữ Hán, La Mã)
        if (/^(Chương|Hồi|Phần|Quyển|Tập|Tiết|Chapter|第)\s*[\d一二三四五六七八九十百千万]+/i.test(line.trim())) return;
        // Bỏ qua dòng ngắn < 5 từ (có thể là tên riêng hoặc tiêu đề phụ)
        if (line.trim().split(/\s+/).length < 5 && /^[A-Z]/.test(line.trim())) return;
        
        const enWords: string[] = [];
        let match: RegExpExecArray | null;
        EN_WORD_PATTERN.lastIndex = 0;
        
        while ((match = EN_WORD_PATTERN.exec(line)) !== null) {
            const phrase = match[1].trim();
            const offset = match.index;
            const isStartOfSentence = offset === 0 || /(?:^|[.!?]\s+)["'“‘«(]?$|^\s+$/.test(line.substring(0, offset));
            
            if (isProperNoun(phrase) && !isStartOfSentence) continue;
            if (WHITELIST_WORDS.has(phrase.toLowerCase())) continue;
            if (customWhitelist.has(phrase.toLowerCase())) continue;
            if (isModernOrGame && GAME_MODERN_WHITELIST.has(phrase.toLowerCase())) continue;
            if (phrase.length <= 2) continue;
            if (COMMON_EN_VI_MAP[phrase.toLowerCase()]) continue;
            
            const words = phrase.split(/\s+/);
            const isDefiniteEnglish = words.some(w => {
                const lower = w.toLowerCase();
                if (lower.length === 0) return false;
                if (lower.length <= 2) return false; // Bỏ qua từ 1-2 ký tự
                
                // Danh sách âm đầu tiếng Việt (không phải tiếng Anh)
                const VI_INITIALS_RX = /^(ch|gh|gi|kh|ngh|ng|nh|ph|qu|th|tr|đ)/;
                if (VI_INITIALS_RX.test(lower)) return false; // Chắc là tiếng Việt không dấu
                
                // Kiểm tra chuỗi phụ âm bất thường (tiếng Anh thường có)
                const hasEnglishConsonantCluster = /[bcdfghjklmnpqrstvwxz]{3,}/.test(lower);
                
                // Kiểm tra âm cuối tiếng Anh không có trong tiếng Việt
                const hasEnglishEnding = /(?:tion|ness|ment|ible|able|ful|less|ous|ish|ive|ize|ise|ify|ary|ery|ory|ship|hood|ward|ways|wise|ld|ft|sk|st|sp|nd|nk|ght|tch|dge|mb|lm|lf|lk|rk|rf|rt|rs|rn|wl|wn|wr|xed|xes|ing|ings|ed|er|ers|est)$/.test(lower);
                
                // Từ có âm cuối tiếng Anh rõ ràng hoặc tổ hợp phụ âm lạ → tiếng Anh
                if (hasEnglishEnding || hasEnglishConsonantCluster) return true;
                
                const initialRegex = /^(b|c|d|f|g|h|j|k|l|m|n|p|q|r|s|t|v|w|x|y|z)?(.*)$/;
                const m = lower.match(initialRegex);
                if (!m) return true;
                
                const remainder = m[2];
                if (remainder.length === 0) return true; 
                
                // Âm cuối tiếng Việt chỉ có: a, ă, â, e, ê, i, o, ô, ơ, u, ư, y
                // và các vần: c, ch, m, n, ng, nh, p, t
                const remainderRegex = /^[aeiouy]{1,3}(c|ch|m|n|ng|nh|p|t)?$/;
                return !remainderRegex.test(remainder);
            });

            if (!isDefiniteEnglish) continue;
            
            enWords.push(phrase);
        }
        
        if (enWords.length > 0) {
            results.push({ lineIndex, line, enWords });
        }
    });
    
    return results;
};

export const applyInlineEnglishFix = (
    translatedContent: string,
    extraMap?: Record<string, string>
): string => {
    const { fixed } = fixInlineEnglish(translatedContent, extraMap);
    return fixed;
};

export const countInlineEnglishOccurrences = (text: string): number => {
    if (!text) return 0;
    const { changes } = fixInlineEnglish(text);
    return changes.length;
};
